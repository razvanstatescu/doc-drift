#!/usr/bin/env node
// Fit the v5 score to src/data/timeline.json: writes tools/audio/arrangements/score-v5.json from the timeline's markers
// and line positions (the same plan every time), then renders public/music/score-v5.wav with arrange.py. No spend.
//   node tools/audio/score-v5.mjs [--dry]
// The plan (V5 brief, R6 technique 16 "one silence"), all from v4's take (music_v2_5, seed 7101):
//   - Night: the take's Night (+4 dB) from source 32 - daySlip, running into the take's own lift on daySlip (no stop);
//   - the 19 s roll: the band strips to bass and ticks from the beat after S10's last word;
//   - THE drop, the film's one silence: the score stops on the last beat at least half a bar before the flag, voice
//     only, then the band (a 3 ms entry) and a sub hit land together on the flag frame;
//   - one bar-line splice after the flag lands the take's final hit (source 144) on endHit;
//   - FIX is low-passed and opens into the snap back: the full band and a small sub hit land on S18's bar line (the
//     downbeat; "Verified", the snapBack marker, follows 2-4 frames later, as the take's first word starts);
//   - a 2-bar riser and a 1-bar high-pass build into endHit; the take's final hit and a sub hit land on it; its
//     C major ring-out is phase-vocoder stretched to the film's last frame, fading to silence.
// Contact (R6): the flag and end hits' transients are on their contact frames (file time = the frame's first sample);
// the snap back resolves on the downbeat that starts S18, because the groove's own kick is there anyway.
import { spawnSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FILMS, PATHS } from './config.mjs';
import { argv, readJson, writeJson } from './lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const OFF = 0.0065; // the take's first-beat offset: file time = grid time + OFF
const SOURCE_LIFT = 32, SOURCE_HIT = 144, SOURCE_DROPOUT = 62; // take seconds (grid): the lift, the final hit, its kick drop-out bar
const r4 = (x) => Math.round(x * 10000) / 10000;

/** The edit's anchors (film seconds) from a v5 timeline. timeline-v5.mjs compares these with the edit's `expect`. */
export function anchorsOf(tl) {
  const fps = tl.fps, sec = (f) => r4(f / fps), m = tl.markers;
  const line = (id) => tl.vo.find((l) => l.id === id);
  const lastWordTo = (id) => line(id).words.at(-1).to;
  const ceilTo = (f, q) => Math.ceil(f / q - 1e-9) * q;
  const floorTo = (f, q) => Math.floor(f / q + 1e-9) * q;
  const flagF = m.flag;
  const s17End = sec(lastWordTo('S17'));
  const snapBar = sec(line('S18').from);
  return {
    daySlip: sec(m.daySlip),
    stripFrom: sec(ceilTo(lastWordTo('S10'), 15)), // the beat after S10's last word
    dropFrom: sec(floorTo(flagF - 30, 15)), // the last beat at least half a bar before the flag
    flag: sec(flagF),
    splice: sec(ceilTo(flagF + 8, 60)), // the first bar line after the landing
    FIX: sec(m.FIX),
    // the filter opens from the first sixteenth after S17's last word, between 1 and 0.25 s before S18's bar line
    openFrom: r4(Math.min(snapBar - 0.25, Math.max(snapBar - 1.0, Math.ceil(s17End / 0.125 - 1e-9) * 0.125))),
    snapBar,
    snapBack: sec(m.snapBack),
    endHit: sec(m.endHit),
    filmEnd: sec(m.filmEnd),
  };
}

export function arrangement(tl) {
  const A = anchorsOf(tl);
  const grid = (filmSec) => r4(filmSec - OFF); // grid time whose file time is this film time
  const night0 = SOURCE_LIFT - A.daySlip; // source second at film 0
  if (night0 < 4) throw new Error(`PROBLEM is longer than the take's Night (${A.daySlip} s)`);
  if (A.splice - A.daySlip + SOURCE_LIFT > SOURCE_DROPOUT + 1e-9) throw new Error('the landing segment would reach the take\'s drop-out bar');
  const reentry = r4(grid(A.flag) + 0.005 + 0.003); // seam = flag frame + 3 ms, so the 3 ms entry starts on the frame
  const seg4From = SOURCE_HIT - (A.endHit - A.splice);
  const ringFrom = A.endHit + 0.25, ringSrc = SOURCE_HIT + 0.25;
  const stretch = r4((A.filmEnd - ringFrom) / 3.5); // 3.5 s of the take's ring-out (-16.6 to -33 dB) fills the close
  const f = (s) => Math.round(s * 30);
  return {
    _comment: `Generated by tools/audio/score-v5.mjs from src/data/timeline.json (do not edit by hand; edit the fitter). v4's take (music_v2_5, seed 7101, 152 s, 120.004 BPM, beats at 0.0065 + k/2 s), no new generation. Film clock = grid clock (frame 0 = grid 0; file time = grid + 0.0065). The take's Night (+4 dB) runs into its own lift on daySlip (film ${A.daySlip} = source ${SOURCE_LIFT}). The roll strips to bass and ticks from ${A.stripFrom}; the film's ONE silence is the drop ${A.dropFrom}-${A.flag} (f${f(A.dropFrom)}-f${f(A.flag)}), voice only; the band (3 ms entry) and a sub hit land together on the flag frame. One bar-line splice at film ${A.splice} (source ${r4(A.splice + night0)} -> ${seg4From}) puts the take's final hit on endHit (film ${A.endHit} = source ${SOURCE_HIT}). FIX is low-passed from ${A.FIX} and opens into the snap back: the full band and a sub hit land on S18's bar line (${A.snapBar}), "Verified" (snapBack ${A.snapBack}) right after. A 2-bar riser and a 1-bar high-pass build into endHit; the hit's C major ring-out is stretched ${stretch}x to the last frame.`,
    source: 'tools/audio/cache/music/score-music_v2_5-s7101.wav',
    out: 'public/music/score-v5.wav',
    beatOffset: OFF,
    durationSec: A.filmEnd,
    startFadeMs: 20,
    endFadeMs: 50,
    peakDb: -3,
    segments: [
      { t0: 0, t1: A.dropFrom, s0: night0, why: `the take's Night from source ${night0}, its own lift on daySlip (source ${SOURCE_LIFT}), the drive, the roll` },
      { t0: A.dropFrom, t1: reentry, silence: true, why: 'the drop: the film\'s one silence, voice only' },
      { t0: reentry, t1: A.splice, s0: r4(reentry + night0), xfMs: 3, why: 'the landing: the band re-enters on the flag frame (3 ms), where the take would be' },
      { t0: A.splice, t1: ringFrom, s0: seg4From, why: 'one bar-line splice; the take\'s final hit (source 144) on endHit' },
      { t0: ringFrom, t1: A.filmEnd, s0: ringSrc, stretch, why: `the ring-out (C major) ${stretch}x slower, to the film's last frame` },
    ],
    sweeps: [
      { type: 'strip', t0: A.stripFrom, t1: A.dropFrom, bassHz: 250, tickHz: 6000, tickGain: 0.3, rampIn: 0.25, rampOut: 0.02, why: 'the 19 s roll: bass and ticks only, until the drop' },
      { type: 'lowpass', points: [[A.FIX, 14000], [A.FIX + 1, 900], [A.openFrom, 900], [A.snapBar, 14000]], why: 'FIX: muffled (900 Hz), opening after S17 into S18\'s downbeat' },
      { type: 'highpass', t0: A.endHit - 2, t1: A.endHit, fromHz: 30, toHz: 600, why: 'the last bar before endHit thins upward; full band on the hit' },
    ],
    gain: [
      { t0: 0, t1: A.daySlip, db: 4, why: 'the Night bed +4 dB, so it is heard under the voice (about 17 dB under it; the Day about 15)' },
      { t0: A.filmEnd - 1, t1: A.filmEnd, db: -60, ramp: true, curve: 'db', why: 'the ring-out fades to silence on the film\'s last frame' },
    ],
    synth: [
      { type: 'riser', t0: A.endHit - 4, t1: A.endHit, db: -16, fromHz: 180, toHz: 2400, why: 'a 2-bar riser into endHit, at its top on the hit' },
    ],
    subHits: [
      { t: r4(grid(A.flag) + 0.004), db: -12, why: `flag: lands with the band on the flag frame (f${f(A.flag)})` },
      { t: A.snapBar, db: -16, why: `snapBack: the full band and this hit on S18's downbeat (f${f(A.snapBar)}); "Verified" at f${f(A.snapBack)}` },
      { t: A.endHit, db: -8, why: 'endHit: the end card lands; doubles the take\'s own final hit' },
    ],
    cues: [
      { id: 'N1', from: 0, to: A.daySlip, what: 'Night (+4 dB): sub pulse, ticking hats, dark pad; 2 loud / 2 quiet bars, rising into the lift' },
      { id: 'D1', from: A.daySlip, to: A.stripFrom, what: 'the take\'s own Day lift on daySlip (kick, backbeat, bright synths), then a steady drive' },
      { id: 'D2', from: A.stripFrom, to: A.dropFrom, what: 'the 19 s roll: the band strips to bass and ticks' },
      { id: 'D3', from: A.dropFrom, to: A.flag, what: 'the drop: the film\'s one silence, voice only ("the page says")' },
      { id: 'D4', from: A.flag, to: A.FIX, what: 'the landing: band and sub hit together on the flag frame; steady drive under AGENTS' },
      { id: 'F1', from: A.FIX, to: A.snapBar, what: 'FIX: low-pass 900 Hz, opening after S17 into the snap back' },
      { id: 'F2', from: A.snapBar, to: A.endHit - 4, what: 'snapBack: full band and a small sub hit on S18\'s downbeat ("Verified" just after); steady drive under JIRA' },
      { id: 'E1', from: A.endHit - 4, to: A.endHit, what: 'build: a 2-bar riser, a 1-bar high-pass into endHit' },
      { id: 'E2', from: A.endHit, to: A.filmEnd, what: `endHit: the take's final hit plus a sub hit; its C major ring-out (${stretch}x) under S21 and S22, fading to silence on the last frame` },
    ],
    expect: { _why: 'the anchors this edit was fitted to (anchorsOf in score-v5.mjs); timeline-v5.mjs marks the score pending when they drift', ...A },
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const tl = readJson(resolve(PATHS.dataDir, FILMS.v5.timeline));
  const arr = arrangement(tl);
  const out = resolve(here, 'arrangements', 'score-v5.json');
  writeJson(out, arr, 1);
  console.log(JSON.stringify(arr.expect));
  if (!argv().dry) {
    const r = spawnSync('python3', ['-I', resolve(here, 'arrange.py'), out], { stdio: 'inherit' });
    if (r.status !== 0) process.exit(r.status ?? 1);
  }
}
